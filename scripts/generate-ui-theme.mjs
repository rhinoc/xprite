import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageRoot = resolve(repositoryRoot, "packages/ui");
const sourceRoot = resolve(packageRoot, "assets/themes/aseprite");
const outputRoot = resolve(packageRoot, "src/base/theme/generated");
const [lightTheme, darkTheme] = await Promise.all([
  readFile(resolve(sourceRoot, "aseprite-light-theme.json"), "utf8").then(JSON.parse),
  readFile(resolve(sourceRoot, "aseprite-dark-theme.json"), "utf8").then(JSON.parse),
]);

function union(name, values) {
  return `export type ${name} =\n${[...new Set(values)]
    .sort()
    .map((value) => `  | ${JSON.stringify(value)}`)
    .join("\n")};`;
}

function normalizeColor(value) {
  const trimmed = value.trim().toLowerCase();
  if (/^#[0-9a-f]{3}$/.test(trimmed))
    return `#${trimmed[1]}${trimmed[1]}${trimmed[2]}${trimmed[2]}${trimmed[3]}${trimmed[3]}`;
  return trimmed;
}

function themeModule(theme, atlasFile, lightColorRoles) {
  const lines = [
    `import themeSheetAssetUrl from "$assets/themes/aseprite/${atlasFile}";`,
    'import type { UiStyleDefinition } from "$/base/theme/theme-types";',
    `export const themeDefinition = ${JSON.stringify(theme, null, 2)} satisfies UiStyleDefinition;`,
    "export const sheetUrl: string = themeSheetAssetUrl;",
  ];
  if (lightColorRoles)
    lines.push(
      `export const lightThemeColorRoles = ${JSON.stringify(lightColorRoles, null, 2)} as const;`,
    );
  return `${lines.join("\n\n")}\n`;
}

const colorsByValue = {};
for (const [role, color] of Object.entries(lightTheme.colors)) {
  const key = normalizeColor(color);
  (colorsByValue[key] ??= []).push(role);
}

const typeContent = [
  "// Generated by scripts/generate-ui-theme.mjs.",
  union("AtlasPartName", [...Object.keys(lightTheme.parts), ...Object.keys(darkTheme.parts)]),
  union("UiColorRole", [...Object.keys(lightTheme.colors), ...Object.keys(darkTheme.colors)]),
  "",
].join("\n\n");

const outputs = new Map([
  [resolve(packageRoot, "src/base/theme/theme-name-types.ts"), typeContent],
  [
    resolve(outputRoot, "themes/aseprite-light.ts"),
    themeModule(lightTheme, "aseprite-theme-sheet.webp"),
  ],
  [
    resolve(outputRoot, "themes/aseprite-dark.ts"),
    themeModule(darkTheme, "aseprite-dark-sheet.webp", colorsByValue),
  ],
]);

for (const [path, content] of outputs) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}
