export const BEAD_TEXT: Readonly<Record<PublicLanguage, BeadCatalog>> = {
  [PublicLanguage.English]: ENGLISH,
  [PublicLanguage.SimplifiedChinese]: SIMPLIFIED_CHINESE,
  [PublicLanguage.Japanese]: JAPANESE,
  [PublicLanguage.Korean]: KOREAN,
  [PublicLanguage.Russian]: RUSSIAN,
  [PublicLanguage.BrazilianPortuguese]: BRAZILIAN_PORTUGUESE,
  [PublicLanguage.Spanish]: SPANISH,
};

export type BeadText = (key: BeadTextKey, values?: Record<string, string | number>) => string;

export function beadText(language: PublicLanguage): BeadText {
  const catalog = BEAD_TEXT[language] ?? ENGLISH;
  return (key, values) => {
    let message: string = catalog[key] ?? ENGLISH[key];
    for (const [name, value] of Object.entries(values ?? {}))
      message = message.split(`{${name}}`).join(String(value));
    return message;
  };
}

/** Labels printed into PNG sheets and PDF pages, in the page language. */
export function beadDocumentLabels(text: BeadText): BeadDocumentLabels {
  return {
    sheetTitle: text("beads.doc.title"),
    sheetMaterials: text("beads.doc.legend"),
    summary: (values) => text("beads.doc.summary", values),
    boardLayout: (values) => text("beads.doc.layout", values),
    overview: (values) => text("beads.doc.overview", values),
    boardPage: (values) => text("beads.doc.board", values),
    boardRange: (values) => text("beads.doc.range", values),
    materials: (values) => text("beads.doc.materials", values),
    materialsContinued: (values) => text("beads.doc.materials.continued", values),
    total: (values) => text("beads.doc.total", values),
    code: text("beads.doc.code"),
    color: text("beads.doc.color"),
    quantity: text("beads.doc.quantity"),
  };
}
