export type MiniToolText = (
  key: MiniToolTextKey,
  values?: Record<string, string | number>,
) => string;

/** Simplified Chinese unless the user picked another language before. */
export function miniToolText(language: PublicLanguage): MiniToolText {
  const table: Readonly<Record<MiniToolTextKey, string>> =
    language === PublicLanguage.SimplifiedChinese ? CHINESE : ENGLISH;
  return (key, values) =>
    table[key].replace(/\{(\w+)\}/g, (match, name: string) => String(values?.[name] ?? match));
}

/** Engine and container messages arrive in English; show the matching copy. */
const ERRORS: readonly [RegExp, MiniToolTextKey][] = [
  [/Xiaohongshu app/i, "error.app"],
  [/no larger than/i, "error.size"],
  [/PNG, JPEG/i, "error.type"],
  [/read this image|pixelate this image/i, "error.read"],
  [/example/i, "error.example"],
];

export function miniToolError(message: string): MiniToolTextKey {
  return ERRORS.find(([pattern]) => pattern.test(message))?.[1] ?? "error.generic";
}
